	[[nodiscard]] constexpr const Record* Find(std::uint32_t a_technique) noexcept
	{
		std::size_t first = 0;
		std::size_t count = kRecordCount;
		while (count != 0) {
			const auto step = count / 2;
			const auto index = first + step;
			if (kRecords[index].technique < a_technique) {
				first = index + 1;
				count -= step + 1;
			} else {
				count = step;
			}
		}
		return first < kRecordCount && kRecords[first].technique == a_technique ? &kRecords[first] : nullptr;
	}

